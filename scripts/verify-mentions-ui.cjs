const { app, BrowserWindow, ipcMain } = require('electron');
const assert = require('node:assert/strict');
const path = require('node:path');
app.disableHardwareAcceleration();
app.setPath('userData', path.resolve(__dirname, '../artifacts/mentions-ui-profile'));
let win;
app.whenReady().then(async () => {
  const agents = ['alpha', 'beta', 'gamma'].map(id => ({ id, name:id, baseName:id, displayName:`Codex · ${id}`, label:'Codex', tool:'codex', mode:'rpc', status:'listening', workspaceId:'w', directory:'C:\\fixture', rpc:{ alive:true, approvals:[] } }));
  const state = { connection:'connected', agents, rooms:[{ id:'g', title:'Group', type:'group', allMembers:true, workspaceId:'w', thread:'g' }], workspaces:[{id:'w',title:'Fixture',directory:'C:\\fixture'}], messages:[], engines:[], connections:[] };
  const sent=[];
  const { installChatFixture } = require('../test/fixtures/chat-api-fixture.cjs');
  await installChatFixture(ipcMain, () => win, { snapshot: () => state, send: async payload => { sent.push(payload); return { receipt: { event_id: sent.length } }; } });
  ipcMain.handle('fixture:state', () => state);
  ipcMain.handle('fixture:send', (_, payload) => { sent.push(payload); return { state }; });
  win = new BrowserWindow({ width:1200,height:900,show:false,webPreferences:{offscreen:true,preload:path.resolve(__dirname,'../test/fixtures/rpc-ui-preload.cjs'),sandbox:true,contextIsolation:true,nodeIntegration:false} });
  win.webContents.on('console-message', event => { if(event.level === 'error') console.error(event.message); });
  await win.loadFile(path.resolve(__dirname,'../renderer/index.html'));
  const run = async source => { try { return await win.webContents.executeJavaScript(source); } catch(e) { console.error(source); throw e; } };
  const until = async source => { const deadline=Date.now()+5000; while(!await run(source)) { if(Date.now()>deadline) throw new Error('Timed out: '+source); await new Promise(r=>setTimeout(r,25)); } };
  await until('document.querySelector("#connection-text").textContent.includes("已连接")');
  await run('document.querySelector("[data-room=g]").click(); document.querySelector("#message-input").focus()');
  await win.webContents.insertText('@');
  await until('!document.querySelector("#mention-menu").hidden');
  // Real pointer events exercise focus transfer between the menu and textarea.
  const point=await run('(() => { const r=document.querySelector("[data-mention]").getBoundingClientRect(); return {x:Math.round(r.x+20),y:Math.round(r.y+15)}; })()');
  win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...point});
  win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...point});
  await until('document.querySelector("#message-input").value === "@alpha "');
  await win.webContents.insertText('@be');
  await until('!document.querySelector("#mention-menu").hidden');
  win.webContents.sendInputEvent({type:'keyDown',keyCode:'Return'});
  win.webContents.sendInputEvent({type:'keyUp',keyCode:'Return'});
  await until('document.querySelector("#message-input").value === "@alpha @beta "');
  assert.equal(sent.length,0,'mention selection must not send');
  await win.webContents.insertText('请@ga');
  await until('!document.querySelector("#mention-menu").hidden');
  await run('document.querySelector("[data-mention]").click()');
  assert.equal(await run('document.querySelector("#message-input").value'),'@alpha @beta 请@gamma ');
  await win.webContents.insertText('检查');
  await run('document.querySelector("#send-button").click()');
  await until('document.querySelector("#message-input").value === ""');
  assert.equal(sent.length,1);
  assert.equal(sent[0].text,'@alpha @beta 请@gamma 检查');
  await run('document.querySelector("[data-action=mention]").click()');
  await until('!document.querySelector("#mention-menu").hidden');
  await run('document.querySelector("[data-mention]").click(); document.querySelector("[data-action=mention]").click()');
  await until('!document.querySelector("#mention-menu").hidden');
  await run('document.querySelectorAll("[data-mention]")[1].click()');
  assert.equal(await run('document.querySelector("#message-input").value'),'@alpha @beta ');
  console.log('Passed: repeated @ using mouse/keyboard, Chinese-adjacent mention, selection does not send, final payload retains all mentions.');
  win.destroy(); app.quit();
}).catch(e => { console.error(e); win?.destroy(); app.exit(1); });
