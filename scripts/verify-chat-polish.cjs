// Frontend-owned checks: no production API, IPC handler or model process.
const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { build } = require('esbuild');
const { createPreviewServer } = require('./dev-ui.cjs');
app.disableHardwareAcceleration();
app.setPath('userData', path.resolve(__dirname, '../artifacts/chat-polish-profile'));
let win, server;
app.whenReady().then(async () => {
  server = createPreviewServer(); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`, errors = [], requests = [];
  win = new BrowserWindow({ width: 1440, height: 960, show: false, webPreferences: { offscreen: true, sandbox: true, contextIsolation: true, nodeIntegration: false } });
  win.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message); });
  win.webContents.session.webRequest.onBeforeRequest((details, callback) => { requests.push(details.url); callback({ cancel: !details.url.startsWith(origin) }); });
  const run = async source => { try { return await win.webContents.executeJavaScript(source); } catch (error) { console.error(source, errors); throw error; } };
  const until = async source => { const deadline = Date.now() + 8000; while (!await run(source)) { if (Date.now() > deadline) throw new Error(`Timeout: ${source}\n${errors.join('\n')}`); await new Promise(resolve => setTimeout(resolve, 30)); } };
  const click = text => run(`(() => { const button = Array.from(document.querySelectorAll('button')).find(b => b.textContent.trim() === ${JSON.stringify(text)}); button.focus(); button.click(); })()`);
  const input = async (selector, value) => { await run(`document.querySelector(${JSON.stringify(selector)}).focus(); document.querySelector(${JSON.stringify(selector)}).select()`); await win.webContents.insertText(value); };
  const capture = async name => { await new Promise(resolve => setTimeout(resolve, 250)); await fs.writeFile(path.resolve(__dirname, `../artifacts/${name}`), (await win.webContents.capturePage()).toPNG()); };
  const key = keyCode => { win.webContents.sendInputEvent({ type: 'keyDown', keyCode }); win.webContents.sendInputEvent({ type: 'keyUp', keyCode }); };
  await win.loadURL(origin);
  await until('document.querySelector("#connection-text")?.textContent === "模拟连接正常"');
  await input('[aria-label="搜索会话"]', 'NO-MATCH');
  await until('Boolean(document.querySelector(".chat-search-empty"))');
  await click('清除搜索');
  await input('[aria-label="搜索会话"]', 'BETA');
  assert.ok(await run(`Boolean(document.querySelector('[data-room="dm:beta"]'))`));
  await input('[aria-label="搜索会话"]', '');
  await input('#message-input', '@al'); await until('Boolean(document.querySelector(".mention-option"))');
  await run('document.querySelector(".mention-option").click()');
  await win.webContents.insertText('@be'); await until('document.querySelector(".mention-option")?.textContent.includes("Beta")');
  await run('document.querySelector(".mention-option").click()');
  await until('document.querySelectorAll(".composer-recipients button").length === 2');
  await run(`document.querySelector('[aria-label="移除 Alpha 的提及"]').click()`);
  await until('document.querySelectorAll(".composer-recipients button").length === 1');
  await win.webContents.insertText('检查'); await run('document.querySelector("#send-button").click()');
  await until('document.querySelector("#message-input").value === ""');
  await until('document.querySelectorAll(".message[data-message-id]").length === 4');
  assert.ok(await run('Array.from(document.querySelectorAll(".message-name")).at(-1).textContent === "Beta"'), 'Removing a chip must remove its recipient and preserve the other range');
  await input('#message-input', '@nobody'); key('Return');
  assert.equal(await run('document.querySelectorAll(".message[data-message-id]").length'), 4, 'Empty mention results must not accidentally submit');
  await input('#message-input', '');
  await click('结果示例'); await until('Boolean(document.querySelector(".result-chart"))');
  assert.ok(await run('document.querySelector(".result-panel").contains(document.activeElement)'));
  async function contrast() {
    const readings = await run(`(() => {
      const rgb = value => value.match(/[\\d.]+/g).map(Number);
      const luminance = c => c.slice(0,3).map(n => n/255).map(n => n <= .04045 ? n/12.92 : ((n+.055)/1.055)**2.4).reduce((s,n,i)=>s+n*[.2126,.7152,.0722][i],0);
      return Array.from(document.querySelectorAll('.result-description,.result-preview-label,.result-metrics dt,.result-metrics dd,.result-tabs button,.result-table-wrap th')).map(el=>{
        let ancestor=el, bg;
        do { bg=rgb(getComputedStyle(ancestor).backgroundColor); ancestor=ancestor.parentElement; } while(bg[3]===0 && ancestor);
        const a=luminance(rgb(getComputedStyle(el).color)), b=luminance(bg);
        return {text:el.textContent,ratio:(Math.max(a,b)+.05)/(Math.min(a,b)+.05)};
      });
    })()`);
    for (const item of readings) assert.ok(item.ratio >= 4.5, `${item.text}: contrast ${item.ratio}`);
  }
  await contrast(); await capture('chat-polish-results-light.png');
  await click('表单'); await until('Boolean(document.querySelector(".result-field input"))');
  assert.equal(await run('document.querySelector(".result-form-actions button").disabled'), true);
  await input('.result-field input', '保留原有设计精髓'); await click('保存本地草稿');
  await until('document.querySelector(".result-form-actions [role=status]").textContent.includes("已保存")');
  await run(`document.querySelector('[data-room="dm:beta"]').click()`);
  assert.equal(await run('document.querySelector(".result-field input").value'), '');
  await input('.result-field input', '独立会话草稿');
  await run('document.querySelector("[data-room=room-design]").click()');
  assert.equal(await run('document.querySelector(".result-field input").value'), '保留原有设计精髓');
  await capture('chat-polish-form.png');
  await run('document.querySelector("#result-tab-form").focus()'); key('Left');
  await until('document.querySelector("#result-tab-table").getAttribute("aria-selected") === "true"');
  assert.equal(await run('document.activeElement.id'), 'result-tab-table');
  await click('概览'); await run('document.querySelector("[aria-label=切换主题]").click()');
  await until('document.documentElement.dataset.theme === "dark"'); await new Promise(resolve => setTimeout(resolve, 300)); await contrast(); await capture('chat-polish-results-dark.png');
  await run('document.querySelector("[aria-label=收起侧栏]").click()'); win.setSize(720, 900);
  await new Promise(resolve => setTimeout(resolve, 150));
  assert.ok(await run('document.documentElement.scrollWidth <= window.innerWidth'));
  assert.ok(await run(`(() => { const r = document.querySelector('[aria-label="关闭结果面板"]').getBoundingClientRect(); return r.width > 0 && r.right <= innerWidth && r.top >= 0; })()`), 'The result close control must remain reachable at narrow widths');
  await capture('chat-polish-results-narrow.png');
  await run('document.querySelector("#result-tab-dashboard").focus()'); key('Escape');
  await until('document.querySelector(".result-panel").hidden');
  await until('document.activeElement.textContent === "结果示例"');
  await run('document.querySelector(".dev-controls").open=true'); await click('权限确认');
  await until('Boolean(document.querySelector(".permission-dialog[open]"))');
  assert.ok(await run('document.querySelector(".approval-source").textContent.includes("产品与设计")'));
  await capture('chat-polish-approval.png'); await click('稍后处理');
  // Mount the real confirmation component with an uncertain result; no production seams are changed.
  const harness = await build({ stdin: { resolveDir: path.resolve(__dirname, '..'), loader: 'tsx', contents: `
    import React,{useState} from 'react'; import {createRoot} from 'react-dom/client'; import {ApprovalCenter} from './renderer/chat/approvals';
    const request={id:'uncertain',agentId:'alpha',roomId:'room',revision:0,kind:'permission',title:'测试确认',summary:'本地测试',directory:'',scopeLabel:'仅本次操作',questions:[],options:[]};
    window.__approvalAttempts=0;
    const client={dispatch:async()=>{window.__approvalAttempts++;throw Object.assign(new Error('网络响应丢失'),{outcome:'unknown'});}};
    const state={connection:'live',approvals:[request],agents:[{id:'alpha',displayName:'Alpha'}],rooms:[{id:'room',title:'来源会话'}]};
    document.querySelector('#chat-root').style.display='none'; const host=document.createElement('div');host.className='chat-app';document.body.append(host);createRoot(host).render(<ApprovalCenter client={client} state={state}/>);
  ` }, bundle: true, write: false, format: 'iife', platform: 'browser', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' } });
  await run(harness.outputFiles[0].text); await until('document.querySelector(".permission-dialog[open]")?.textContent.includes("测试确认")');
  await click('允许本次'); await until('Boolean(document.querySelector(".approval-outcome"))');
  assert.equal(await run('Array.from(document.querySelectorAll(".permission-actions button")).every(b=>b.disabled)'), true);
  await click('稍后处理'); await until('!document.querySelector(".permission-dialog")');
  await run('Array.from(document.querySelectorAll(".permission-badge")).at(-1).click()');
  await until('Boolean(document.querySelector(".permission-dialog"))');
  assert.equal(await run('Array.from(document.querySelectorAll(".permission-actions button")).every(b=>b.disabled)'), true);
  assert.equal(await run('window.__approvalAttempts'), 1);
  assert.equal(requests.filter(url => url.includes('/api/')).length, 0);
  assert.deepEqual(errors, []);
  console.log('Passed: recipient removal, search, json-render dashboard/table/form, per-room local drafts, tab keyboard/focus, light/dark contrast, narrow layout, approval source and no repeated uncertain decision.');
  win.destroy(); server.close(); app.quit();
}).catch(error => { console.error(error); win?.destroy(); server?.close(); app.exit(1); });
