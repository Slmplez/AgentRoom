const { app, BrowserWindow } = require('electron');
const { build } = require('esbuild');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const { createPreviewServer } = require('./dev-ui.cjs');
app.disableHardwareAcceleration();
app.setPath('userData', path.resolve(__dirname, '../artifacts/rich-messages-profile'));
let win, server;
app.whenReady().then(async () => {
  server = createPreviewServer(); await new Promise(r => server.listen(0, '127.0.0.1', r));
  win = new BrowserWindow({ show: false, width: 1000, height: 800, webPreferences: { offscreen: true, sandbox: true, contextIsolation: true, nodeIntegration: false } });
  await win.loadURL(`http://127.0.0.1:${server.address().port}`);
  const run = s => win.webContents.executeJavaScript(s);
  const until = async s => { const end=Date.now()+15000; while(!await run(s)) { if(Date.now()>end) throw Error(`Timed out: ${s}`); await new Promise(r=>setTimeout(r,50)); } };
  await until('Boolean(document.querySelector("#message-input"))');
  await run('document.querySelector("#message-input").focus()');
  await win.webContents.insertText('## 富文本展示\n\n| 项目 | 状态 |\n| --- | --- |\n| Markdown | 已支持 |\n| Mermaid | 已支持 |\n\n```mermaid\nflowchart LR\n A[讨论] --> B[执行] --> C[报告]\n```');
  await run('document.querySelector("#send-button").click()');
  await until('Boolean(document.querySelector(".mermaid-diagram svg"))');
  assert.ok(await run('document.querySelectorAll(".message-bubble table td").length >= 4'));
  await run('document.querySelector(".mermaid-diagram").scrollIntoView({block:"center"})');
  await new Promise(r => setTimeout(r, 600));
  await fs.mkdir(path.resolve(__dirname, '../artifacts'), { recursive: true });
  await fs.writeFile(path.resolve(__dirname, '../artifacts/rich-messages.png'), (await win.webContents.capturePage()).toPNG());
  const fixture = await build({ stdin: { resolveDir: path.resolve(__dirname, '..'), loader: 'tsx', contents: `
    import React from 'react'; import {createRoot} from 'react-dom/client'; import {ChatThread} from './renderer/chat/thread';
    const host=document.createElement('div'); host.className='chat-app'; document.body.replaceChildren(host);
    const root=createRoot(host);
    window.renderRich=text=>root.render(<ChatThread messages={[{id:'rich',role:'assistant',text,authorName:'Alpha',tools:[],artifactRefs:[],status:'complete'}]} agents={[]} portrait={()=>''} showDiff={()=>{}}/>);
    window.renderRich('| 项目 | 状态 |\\n| --- | --- |\\n| 布局 | 已讨论 |');
  ` }, bundle: true, write: false, format: 'iife', platform: 'browser', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' } });
  await run(fixture.outputFiles[0].text);
  await until('Boolean(document.querySelector(".message-bubble"))');
  assert.equal(await run('document.querySelectorAll(".message-bubble table td").length'), 2, 'Markdown table must render as cells, not literal pipes');
  await run(`window.renderRich(${JSON.stringify('```mermaid\nflowchart LR\n A[开始] --> B[完成]\n```')})`);
  await until('Boolean(document.querySelector(".mermaid-diagram svg"))');
  assert.ok(await run('document.querySelector(".mermaid-diagram").textContent.includes("完成")'));
  await run(`window.renderRich(${JSON.stringify('```mermaid\nnot valid diagram\n```')})`);
  await until('Boolean(document.querySelector(".mermaid-fallback"))');
  assert.equal(await run('document.querySelectorAll(".mermaid-diagram svg").length'), 0);
  await run(`window.renderRich(${JSON.stringify('```mermaid\nflowchart LR\n A --> C[恢复]\n```')})`);
  await until('document.querySelector(".mermaid-diagram svg")?.textContent.includes("恢复")');
  await run('document.documentElement.dataset.theme="dark"');
  await until('document.querySelector(".mermaid-diagram")?.dataset.theme === "dark"');
  await run(`window.renderRich(${JSON.stringify('<script>window.richUnsafe=true</script>\n\n[bad](javascript:alert(1))\n\n```js\nconst x = 1;\n```')})`);
  await until('Boolean(document.querySelector("code"))');
  assert.equal(await run('Boolean(window.richUnsafe || document.querySelector(".message-bubble script") || document.querySelector("a[href^=javascript]"))'), false);
  console.log('Passed: GFM tables, Mermaid SVG, invalid-source fallback, recovery, theme changes and inert Markdown.');
}).catch(e=>{console.error(e); process.exitCode=1;}).finally(()=>{win?.destroy();server?.close();app.exit(process.exitCode || 0);});
