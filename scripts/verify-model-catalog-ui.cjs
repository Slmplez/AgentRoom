const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { createPreviewServer } = require('./dev-ui.cjs');
app.disableHardwareAcceleration();
app.setPath('userData', path.resolve(__dirname, '../artifacts/model-catalog-ui-profile'));
let win, server;
app.whenReady().then(async () => {
  server = createPreviewServer(); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`, errors = [];
  win = new BrowserWindow({ show: false, width: 1400, height: 1000, webPreferences: { offscreen: true, sandbox: true, contextIsolation: true, nodeIntegration: false } });
  win.webContents.on('console-message', e => { if (e.level === 'error') errors.push(e.message); });
  const run = async code => { try { return await win.webContents.executeJavaScript(code); } catch (error) { console.error(code, errors); throw error; } };
  const until = async code => { const end = Date.now() + 8000; while (!await run(code)) { if (Date.now() > end) throw new Error(`${code}\n${errors}\n${await run('document.body.textContent.slice(-3000)')}`); await new Promise(resolve => setTimeout(resolve, 25)); } };
  const click = text => run(`Array.from(document.querySelectorAll('button')).find(b => b.textContent.trim() === ${JSON.stringify(text)} && b.getClientRects().length).click()`);
  const input = async (selector, value) => { await run(`document.querySelector(${JSON.stringify(selector)}).focus(); document.querySelector(${JSON.stringify(selector)}).select()`); await win.webContents.insertText(value); };
  const select = (selector, value) => run(`(() => { const el=document.querySelector(${JSON.stringify(selector)}); el.value=${JSON.stringify(value)}; el.dispatchEvent(new Event('change',{bubbles:true})); })()`);
  await win.loadURL(origin); await until('document.querySelector("#connection-text")?.textContent === "演示模式"');
  await run('document.querySelector("[aria-label=设置]").click()'); await until('Array.from(document.querySelectorAll("button")).some(b=>b.textContent === "连接兼容网关")'); await click('连接兼容网关');
  await until('document.querySelector("input[name=name]")?.value === "兼容网关"');
  await select('select[name=authMode]', 'none');
  assert.equal(await run('document.querySelector("input[name=model]").value'), '');
  await click('测试连接'); await until('document.querySelector("#settings-models")?.children.length === 3');
  await input('input[name=model]', 'example'); await until('document.querySelector("[data-model-details]")?.textContent.includes("声明匹配")');
  assert.match(await run('document.querySelector("[data-model-details]").textContent'), /图片：支持/);
  await input('input[name=model]', 'text-only'); await until('document.querySelector("[data-model-details]")?.textContent.includes("不可用")');
  await input('input[name=model]', 'example'); await click('保存连接');
  await until('Boolean(document.querySelector(".settings-row"))');
  await run('document.querySelector("[aria-label=关闭设置]").click(); document.querySelector(".sidebar-create").open=true'); await click('添加 Agent');
  await until(`Boolean(document.querySelector('section[aria-label="添加 Agent"] select'))`);
  const section = 'section[aria-label="添加 Agent"]';
  await until(`Array.from(document.querySelectorAll('${section} select'))[1]?.options.length > 1`);
  const pickConnection = await run(`Array.from(document.querySelectorAll('${section} select'))[1].outerHTML`);
  assert.match(pickConnection, /兼容网关/);
  const connectionId = await run(`Array.from(document.querySelectorAll('${section} select'))[1].options[1].value`);
  await select(`${section} select:nth-of-type(1)`, 'codex');
  // Select by the visible field label, independent of other settings tabs kept mounted.
  await run(`(() => { const el=Array.from(document.querySelectorAll('${section} label')).find(l=>l.textContent.startsWith('连接方案')).querySelector('select'); el.value=${JSON.stringify(connectionId)}; el.dispatchEvent(new Event('change',{bubbles:true})); })()`);
  await until(`document.querySelector('${section} #launch-models')?.children.length === 3`);
  await input(`${section} input[name=model]`, 'text-only');
  await until(`document.querySelector('${section} input[name=model]')?.validationMessage.includes('工具调用')`);
  await input(`${section} input[name=model]`, 'unverified');
  await until(`document.querySelector('${section} [data-model-details]')?.textContent.includes('待验证')`);
  assert.equal(await run(`document.querySelector('${section} input[name=model]').validationMessage`), '');
  await input(`${section} input[name=model]`, 'example');
  await until(`document.querySelector('${section} [data-model-details]')?.textContent.includes('示例工具模型')`);
  await run('document.getAnimations().forEach(animation => animation.finish())');
  await new Promise(resolve => setTimeout(resolve, 350));
  await fs.mkdir(path.resolve(__dirname, '../artifacts'), { recursive: true });
  await fs.writeFile(path.resolve(__dirname, '../artifacts/model-catalog-ui.png'), (await win.webContents.capturePage()).toPNG());
  await run(`document.querySelector('${section} button.primary').click()`); await until('!document.querySelector(".settings-dialog").open');
  assert.deepEqual(errors, []);
  console.log('Passed: generic gateway preset; discovery before model selection; declared, unsupported and unknown capabilities; launch validation and successful Mock launch.');
  win.destroy(); server.close(); app.quit();
}).catch(error => { console.error(error); win?.destroy(); server?.close(); app.exit(1); });
