const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict'), path = require('node:path'), fs = require('node:fs/promises');
const { createPreviewServer } = require('./dev-ui.cjs');
app.disableHardwareAcceleration(); app.setPath('userData', path.resolve(__dirname, '../artifacts/preview-modes-profile'));
let win, server;
app.whenReady().then(async () => {
  server = createPreviewServer(); await new Promise(r => server.listen(0, '127.0.0.1', r));
  win = new BrowserWindow({ width: 1440, height: 960, show: false, webPreferences: { offscreen: true, sandbox: true, contextIsolation: true } });
  const errors = []; win.webContents.on('console-message', e => { if (e.level === 'error') errors.push(e.message); });
  const run = s => win.webContents.executeJavaScript(s);
  const until = async s => { const end = Date.now() + 9000; while (!await run(s)) { if (Date.now() > end) throw Error(s); await new Promise(r => setTimeout(r, 30)); } };
  const click = label => run(`(() => { const b = Array.from(document.querySelectorAll('button')).find(b => b.textContent.trim() === ${JSON.stringify(label)} && b.getBoundingClientRect().width); b.focus(); b.click(); })()`);
  const scenario = async label => { await run('document.querySelector(".dev-controls").open=true'); await click(label); await run('document.querySelector(".dev-controls").open=false'); };
  await win.loadURL(`http://127.0.0.1:${server.address().port}`);
  await until('document.querySelector("#connection-text")?.textContent === "演示模式"');
  await run('document.querySelector("#message-input").focus()'); await win.webContents.insertText('保留群聊草稿');
  await click('结果示例'); await until('Boolean(document.querySelector(".preview-summary"))');
  await click('表单'); await click('完整');
  await run('document.querySelector(".result-field input").focus()'); await win.webContents.insertText('交付要求');
  await click('简短'); await click('完整');
  assert.equal(await run('document.querySelector(".result-field input").value'), '交付要求');
  await run('document.querySelector("[aria-label=关闭结果面板]").click()');
  await scenario('发布模拟报告'); await run('document.querySelector("[data-artifact-version]").click()');
  await until('Boolean(document.querySelector(".artifact-panel .preview-summary"))');
  await click('完整'); await until('Boolean(document.querySelector(".artifact-panel .result-section"))');
  await click('简短'); await click('返回对话');
  await scenario('工具与差异'); await click('查看变更');
  await until('Boolean(document.querySelector(".diff-preview .preview-summary"))');
  assert.equal(await run('document.querySelectorAll("diffs-container").length'), 0, 'Summary must not mount the full diff');
  assert.ok(await run('document.querySelector(".diff-preview").textContent.includes("新增")'));
  await click('完整'); await until('Boolean(document.querySelector("diffs-container")?.shadowRoot?.querySelector("code"))');
  await click('并排'); await until('Boolean(document.querySelector("diffs-container")?.shadowRoot?.querySelector("[data-diff-type=split]"))');
  await until('!document.querySelector(".diff-preview [role=status]")');
  await new Promise(r => setTimeout(r, 200));
  await fs.mkdir(path.resolve(__dirname, '../artifacts'), { recursive: true });
  await fs.writeFile(path.resolve(__dirname, '../artifacts/preview-full.png'), (await win.webContents.capturePage()).toPNG());
  await click('简短'); win.setSize(650, 900); await new Promise(r => setTimeout(r, 250));
  assert.ok(await run('document.documentElement.scrollWidth <= innerWidth'));
  await fs.writeFile(path.resolve(__dirname, '../artifacts/preview-short-narrow.png'), (await win.webContents.capturePage()).toPNG());
  await run('document.querySelector(".diff-preview h2").focus()'); win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' });
  await until('!document.querySelector(".diff-preview")');
  assert.equal(await run('document.querySelector("#message-input").value'), '保留群聊草稿');
  assert.equal(await run('document.activeElement.textContent.trim()'), '查看变更');
  await click('查看变更'); await run('document.querySelector("[data-room=room-code]").click()');
  await until('!document.querySelector(".diff-preview")');
  assert.deepEqual(errors, []);
  console.log('Passed: short/full reports and json-render, form/chat drafts, lazy sidebar Diff, split view, narrow layout, Escape/focus and room isolation.');
  win.destroy(); server.close(); app.quit();
}).catch(e => { console.error(e); win?.destroy(); server?.close(); app.exit(1); });
