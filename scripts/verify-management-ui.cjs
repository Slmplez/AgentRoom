const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const path = require('node:path');
const { createPreviewServer } = require('./dev-ui.cjs');
app.disableHardwareAcceleration();
app.setPath('userData', path.resolve(__dirname, '../artifacts/management-ui-profile'));
let win, server;
app.whenReady().then(async () => {
  const errors = [], requests = [];
  server = createPreviewServer(); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  win = new BrowserWindow({ show: false, width: 1400, height: 940, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } });
  win.webContents.on('console-message', e => { if (e.level === 'error') errors.push(e.message); });
  win.webContents.session.webRequest.onBeforeRequest((details, callback) => { requests.push(details.url); callback({ cancel: !details.url.startsWith(origin) }); });
  const run = code => win.webContents.executeJavaScript(code);
  const until = async code => { const end = Date.now() + 6000; while (!await run(code)) { if (Date.now() > end) throw new Error(`${code}\n${errors.join('\n')}\n${await run('document.body.textContent.slice(-2000)')}`); await new Promise(resolve => setTimeout(resolve, 25)); } };
  const click = selector => run(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const fill = (selector, value) => run(`document.querySelector(${JSON.stringify(selector)}).value=${JSON.stringify(value)}`);
  await win.loadURL(`${origin}/workbench.html`);
  await until('document.querySelectorAll(".conversation-item").length > 0');
  assert.equal(await run('typeof window.agentRoom'), 'undefined');
  assert.match(await run('document.querySelector(".local-badge").textContent'), /模拟/);
  await run('document.querySelector("[data-action=connections]").click(); document.querySelector("[data-action=launch]").click()');
  await new Promise(resolve => setTimeout(resolve, 100));
  assert.equal(await run('document.querySelector("#modal-title").textContent'), '启动 Agent', 'Late connection response cannot replace newer modal');
  await click('[data-action=close-modal]');
  await click('[data-action=connections]'); await until('Boolean(document.querySelector("#connection-name"))');
  await fill('#connection-name', '模拟连接'); await fill('#connection-model', 'example'); await fill('#connection-auth', 'none');
  await run('window.AgentRoomChat.controls.failNext("saveConnection")');
  await click('[data-action=connection-save]'); await until('document.querySelector("#toast").textContent.includes("模拟")');
  assert.equal(await run('document.querySelector("#connection-name").value'), '模拟连接');
  await click('[data-action=connection-save]'); await until('document.querySelector(".connection-profile")?.textContent.includes("模拟连接")');
  await click('[data-action=connection-test]'); await until('document.querySelector("#connection-test-result")?.textContent.includes("模拟连接检查通过")');
  await click('[data-action=connection-delete]'); await until('!document.querySelector(".connection-profile")');
  await click('[data-action=close-modal]');
  await click('[data-action=capabilities]'); await until('Boolean(document.querySelector("#cap-name"))');
  await fill('#cap-name', '模拟 MCP'); await fill('#cap-command', 'example');
  await click('[data-cap-action=save-server]'); await until('document.querySelector(".cap-server-item")?.textContent.includes("模拟 MCP")');
  await click('[data-cap-action=test]'); await until('document.querySelector("#cap-test-result")?.textContent.includes("模拟连接成功")');
  await click('[data-cap-tab=skills]'); await until('Boolean(document.querySelector("#cap-skill-dir"))');
  await fill('#cap-skill-dir', 'mock://skill'); await click('[data-cap-action=import-skill]'); await until('Boolean(document.querySelector(".cap-skill"))');
  await click('[data-action=close-modal]');
  await run('window.AgentRoomChat.controls.telemetry()');
  await click('[data-action=usage]'); await until('document.querySelectorAll(".usage-calendar .usage-cell").length === 364');
  assert.match(await run('document.querySelector("#usage-dashboard").textContent'), /1 次用量未知/);
  await click('[data-action=close-modal]');
  await click('[data-action=launch]'); await until('Boolean(document.querySelector("#agent-directory"))');
  await click('[data-engine=pi]'); await click('[data-action=launch-agent]');
  await until('document.body.textContent.includes("mock-agent-") && !document.querySelector(".modal")');
  await click('[data-action=new-room]'); await fill('#room-name', '模拟小队'); await click('[data-action=create-room]');
  await until('document.querySelector(".header-title")?.textContent.includes("模拟小队")');
  await click('[data-action=edit-members]'); await until('Boolean(document.querySelector("[data-save-members]"))');
  await click('[data-save-members]'); await until('!document.querySelector(".modal")');
  await click('[data-remove-agent]'); await click('[data-confirm-remove]'); await until('!document.querySelector(".modal")');
  assert.equal(requests.filter(url => url.includes('/api/')).length, 0);
  assert.deepEqual(errors, []);
  console.log('Passed: pure browser Mock connections, MCP/Skills, usage, Agent launch/removal and room membership; zero production API requests.');
  win.destroy(); server.close(); app.quit();
}).catch(error => { console.error(error); win?.destroy(); server?.close(); app.exit(1); });
