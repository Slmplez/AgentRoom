const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { createPreviewServer } = require('./dev-ui.cjs');
app.disableHardwareAcceleration();
app.setPath('userData', path.resolve(__dirname, '../artifacts/chat-ui-profile'));
let win, server;
app.whenReady().then(async () => {
  server = createPreviewServer(); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`, errors = [], requests = [];
  win = new BrowserWindow({ width: 1400, height: 940, show: false, webPreferences: { offscreen: true, sandbox: true, contextIsolation: true, nodeIntegration: false } });
  win.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message); });
  win.webContents.session.webRequest.onBeforeRequest((details, callback) => { requests.push(details.url); callback({ cancel: !details.url.startsWith(origin) }); });
  await win.loadURL(origin);
  const run = async source => { try { return await win.webContents.executeJavaScript(source); } catch (error) { console.error(source, errors); throw error; } };
  const capture = async name => { await new Promise(resolve => setTimeout(resolve, 250)); await fs.writeFile(path.resolve(__dirname, `../artifacts/${name}`), (await win.webContents.capturePage()).toPNG()); };
  const until = async source => { const end = Date.now() + 9000; while (!await run(source)) { if (Date.now() > end) throw new Error(`Timed out: ${source}\n${errors.join('\n')}`); await new Promise(resolve => setTimeout(resolve, 30)); } };
  const clickText = async text => run(`Array.from(document.querySelectorAll('button')).find(b => b.textContent.trim() === ${JSON.stringify(text)}).click()`);
  const setInput = async value => { await run('document.querySelector("#message-input").focus(); document.querySelector("#message-input").select()'); await win.webContents.insertText(value); };
  const key = code => { win.webContents.sendInputEvent({ type: 'keyDown', keyCode: code }); win.webContents.sendInputEvent({ type: 'keyUp', keyCode: code }); };
  await until('document.querySelector("#connection-text")?.textContent === "演示模式"');
  assert.equal(await run('typeof window.agentRoom'), 'undefined', 'Mock must work without a preload or Electron business bridge');
  await until('document.querySelectorAll(".message[data-message-id]").length === 2');
  // Font names alone can silently fall back. Require actual local font faces,
  // including italic/extended Latin, while all external requests are blocked.
  for (const family of ['Inter', 'Newsreader', 'JetBrains Mono']) {
    for (const style of ['normal', 'italic']) {
      const loaded = await run(`document.fonts.load('${style} 500 15px "${family}"', 'Agent Ā').then(faces => faces.map(face => face.status))`);
      assert.ok(loaded.length > 0 && loaded.every(status => status === 'loaded'), `${family} ${style} must load locally`);
    }
  }
  await new Promise(resolve => setTimeout(resolve, 200));
  await fs.mkdir(path.resolve(__dirname, '../artifacts'), { recursive: true });
  await capture('chat-g1-light.png');
  await setInput('@');
  await until('document.querySelectorAll(".mention-option").length === 3');
  const point = await run('(() => { const r = document.querySelector(".mention-option").getBoundingClientRect(); return {x:Math.round(r.x+20),y:Math.round(r.y+12)} })()');
  win.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...point });
  win.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...point });
  await until('document.querySelector("#message-input").value === "@alpha "');
  await win.webContents.insertText('请@be');
  await until('document.querySelectorAll(".mention-option").length === 1'); key('Return');
  await until('document.querySelector("#message-input").value === "@alpha 请@beta "');
  assert.equal(await run('document.querySelectorAll(".message[data-message-id]").length'), 2, 'Selecting a mention must not submit: ' + await run('JSON.stringify(Array.from(document.querySelectorAll(".message[data-message-id]")).map(el => ({id:el.dataset.messageId,text:el.textContent.slice(0,80)})))'));
  await win.webContents.insertText('一起检查');
  await run('document.querySelector("#send-button").click()');
  await until('document.querySelectorAll(".message[data-message-id]").length === 5');
  const replyIds = await run('Array.from(document.querySelectorAll(".message[data-message-id]")).slice(-2).map(el => el.dataset.messageId)');
  await until('!document.querySelector(".chat-thinking") && document.querySelector("#messages").textContent.includes("这是模拟回复")');
  assert.deepEqual(await run('Array.from(document.querySelectorAll(".message[data-message-id]")).slice(-2).map(el => el.dataset.messageId)'), replyIds);
  await setInput('中文输入草稿');
  await run('document.querySelector("#message-input").dispatchEvent(new CompositionEvent("compositionstart",{bubbles:true})); document.querySelector("#message-input").dispatchEvent(new KeyboardEvent("keydown",{key:"Enter",bubbles:true,isComposing:true}))');
  assert.equal(await run('document.querySelectorAll(".message[data-message-id]").length'), 5);
  await run(`document.querySelector('#message-input').dispatchEvent(new CompositionEvent('compositionend',{bubbles:true})); document.querySelector('[data-room="dm:beta"]').click()`);
  await until('document.querySelector(".header-title").textContent === "Beta"');
  await setInput('私聊草稿');
  await run('document.querySelector("[data-room=room-design]").click()');
  await until('document.querySelector("#message-input").value === "中文输入草稿"');
  await run('document.querySelector(".dev-controls").open = true');
  await clickText('工具与差异');
  await until('Boolean(document.querySelector(".tool-trace"))');
  assert.equal(await run('document.querySelector(".tool-trace").open'), false);
  await run('document.querySelector(".tool-trace > summary").click(); document.querySelectorAll(".tool-step > summary")[1].click()');
  await clickText('推进流式输出');
  assert.equal(await run('document.querySelector(".tool-trace").open'), true);
  await run('document.querySelector("[data-room=room-code]").click()');
  await run('document.querySelector("[data-room=room-design]").click()');
  assert.equal(await run('document.querySelector(".tool-trace").open'), true, 'Expansion survives room switches');
  await clickText('查看文件差异');
  await until('Boolean(document.querySelector("diffs-container")?.shadowRoot?.textContent.includes("一起完成下一件事"))');
  assert.match(await run('getComputedStyle(document.querySelector("diffs-container").shadowRoot.querySelector("code")).fontFamily'), /JetBrains Mono/, 'Diff code must use the shared monospace font');
  await clickText('并排');
  await until('Boolean(document.querySelector("diffs-container")?.shadowRoot?.querySelector("[data-diff-type=split]"))');
  await capture('chat-g1-diff.png');
  await clickText('关闭');
  await clickText('无效差异');
  await run('(() => { const trace=[...document.querySelectorAll(".tool-trace")].at(-1); trace.querySelector("summary").click(); trace.querySelectorAll(".tool-step > summary")[1].click(); [...trace.querySelectorAll("button")].find(b=>b.textContent.includes("查看文件差异")).click(); })()');
  await until('Boolean(document.querySelector(".chat-diff-dialog [role=alert]")?.textContent.includes("无法显示差异"))');
  await clickText('关闭');
  await clickText('输出过期');
  await run('[...document.querySelectorAll(".tool-trace")].at(-1).querySelector("button").click()');
  await until('[...document.querySelectorAll(".tool-trace")].at(-1).textContent.includes("已过期")');
  await clickText('用户提问');
  await until('Boolean(document.querySelector(".permission-dialog[open]"))');
  await run('document.querySelector(".permission-dialog input[type=checkbox]").click()');
  await clickText('稍后处理');
  await until('!document.querySelector(".permission-dialog")');
  await run('document.querySelector(".permission-badge").click()');
  await until('Boolean(document.querySelector(".permission-dialog input[type=checkbox]")?.checked)');
  await clickText('提交回答');
  await until('!document.querySelector(".permission-dialog")');
  await clickText('权限确认');
  await until('Boolean(document.querySelector(".permission-dialog[open]"))');
  await capture('chat-g1-approval.png');
  await clickText('使请求失效');
  await until('!document.querySelector(".permission-dialog")');
  await clickText('模拟断线');
  await until('document.querySelector("#send-button").disabled');
  assert.equal(await run('document.querySelector("#message-input").value'), '中文输入草稿');
  await clickText('恢复连接');
  await until('!document.querySelector("#send-button").disabled');
  await clickText('长对话');
  await until('document.querySelectorAll(".message[data-message-id]").length > 35');
  await run('document.querySelector(".dev-controls").open=false; document.querySelector("#messages").scrollTop=50');
  await new Promise(resolve => setTimeout(resolve, 100));
  await clickText('推进流式输出');
  await new Promise(resolve => setTimeout(resolve, 100));
  assert.ok(await run('document.querySelector("#messages").scrollTop < 100'), 'Reading history must not be pulled to the bottom');
  await run('document.querySelector("[aria-label=切换主题]").click()');
  await until('document.documentElement.dataset.theme === "dark"');
  await capture('chat-g1-dark.png');
  await run('document.querySelector("[aria-label=收起侧栏]").click()');
  win.setSize(720, 900);
  await new Promise(resolve => setTimeout(resolve, 150));
  assert.ok(await run('document.documentElement.scrollWidth <= window.innerWidth'), 'Narrow layout must not overflow horizontally');
  await capture('chat-g1-narrow.png');
  await clickText('空工作区');
  await until('document.querySelectorAll("[data-room]").length === 0');
  await clickText('重置场景');
  await until('document.querySelectorAll(".message[data-message-id]").length === 2');
  assert.equal(requests.filter(url => url.includes('/api/')).length, 0, 'Mock must not contact production APIs');
  assert.deepEqual(errors, []);
  console.log('Passed: standalone Mock, assistant-ui messages, repeated @, separate Agent streams, IME, drafts, tools, approvals, expiry, reconnect, scroll, Pierre diff, themes and narrow layout.');
  win.destroy(); server.close(); app.quit();
}).catch(error => { console.error(error); win?.destroy(); server?.close(); app.exit(1); });
